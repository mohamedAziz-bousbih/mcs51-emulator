#!/usr/bin/env python3
"""Generate all_opcodes.a51: one instruction for each of the 256 opcodes.

The text is rendered from the instruction table of tools/asm51.py, in the
canonical syntax of the C disassembler (hex numbers with an 'h' suffix, SFR
and bit names). Two tests use the file:

  tests/asm/test_asm51.py   assembling it yields opcodes 00h..FFh in order
  tests/test_disasm.c       disassembling all_opcodes.hex reproduces the text

so the Python instruction table and the C opcode table/disassembler are
cross-checked against each other for every opcode.

Usage: python tests/vectors/gen_all_opcodes.py [output.a51]
"""

import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[2] / "tools"))
import asm51  # noqa: E402

ORIGIN = 0x1000
DIRECT = ["30h", "P1", "ACC", "7Fh", "B", "SP", "DPL", "TCON", "0C8h"]
BITS = ["P1.0", "TR0", "20h.3", "ACC.7", "2Fh.7", "CY", "EA", "TI", "P3.2", "PSW.1"]
IMMEDIATE = ["#5Ah", "#0A5h", "#00h", "#0FFh", "#12h"]
IMMEDIATE16 = ["#1234h", "#0ABCDh"]
RELATIVE = [0, 5, -2, 127, -128, 16, -16]
PAGE_LOW = [0x00, 0x23, 0xFF, 0x80]
LONG = ["1234h", "0ABCDh", "0000h", "0FFFFh"]
SIZE = {"#": 1, "#16": 2, "dir": 1, "bit": 1, "/bit": 1, "rel": 1, "a11": 1, "a16": 2}


def hexnum(value: int, digits: int) -> str:
    text = f"{value:0{digits}X}"
    return ("0" if text[0] in "ABCDEF" else "") + text + "h"


def opcode_forms():
    """opcode -> (mnemonic, pattern, register number or None)."""
    forms = {}
    for mnemonic, entries in asm51.INSTRUCTIONS.items():
        if mnemonic in ("JMP", "CALL"):
            # generic forms: only JMP @A+DPTR has an opcode of its own
            entries = [e for e in entries if e[1] == 0x73]
        for pattern, base in entries:
            count = 8 if "Rn" in pattern else 2 if "@Ri" in pattern else 1
            if pattern and pattern[0] == "a11":
                for page in range(8):
                    forms[base | page << 5] = (mnemonic, pattern, None)
                continue
            for reg in range(count):
                forms[base + reg] = (mnemonic, pattern, reg if count > 1 else None)
    return forms


def render(op: int, mnemonic: str, pattern, reg, address: int, counter: list) -> str:
    size = 1 + sum(SIZE.get(slot, 0) for slot in pattern)
    next_pc = address + size
    operands = []
    for slot in pattern:
        n = counter[0]
        counter[0] += 1
        if slot == "Rn":
            operands.append(f"R{reg}")
        elif slot == "@Ri":
            operands.append(f"@R{reg}")
        elif slot == "#":
            operands.append(IMMEDIATE[n % len(IMMEDIATE)])
        elif slot == "#16":
            operands.append(IMMEDIATE16[n % len(IMMEDIATE16)])
        elif slot == "dir":
            operands.append(DIRECT[n % len(DIRECT)])
        elif slot == "bit":
            operands.append(BITS[n % len(BITS)])
        elif slot == "/bit":
            operands.append("/" + BITS[n % len(BITS)])
        elif slot == "rel":
            operands.append(hexnum(next_pc + RELATIVE[n % len(RELATIVE)], 4))
        elif slot == "a11":
            target = (next_pc & 0xF800) | (op & 0xE0) << 3 | PAGE_LOW[n % len(PAGE_LOW)]
            operands.append(hexnum(target, 4))
        elif slot == "a16":
            operands.append(LONG[n % len(LONG)])
        else:
            operands.append(slot)
    text = f"{mnemonic:<6}{','.join(operands)}" if operands else mnemonic
    return text.rstrip(), size


def generate() -> str:
    forms = opcode_forms()
    lines = [
        "; all_opcodes.a51 - one instruction per opcode 00h..FFh, generated by",
        "; gen_all_opcodes.py in the canonical syntax of the disassembler.",
        "; A5h is reserved and appears as a DB byte.",
        "",
        f"        ORG   {hexnum(ORIGIN, 4)}",
    ]
    address = ORIGIN
    counter = [0]
    for op in range(256):
        if op == 0xA5:
            lines.append(f"        DB    {hexnum(op, 2)}")
            address += 1
            continue
        mnemonic, pattern, reg = forms[op]
        text, size = render(op, mnemonic, pattern, reg, address, counter)
        lines.append(f"        {text}")
        address += size
    lines.append("")
    lines.append("        END")
    return "\n".join(lines) + "\n"


def main() -> int:
    out = Path(sys.argv[1]) if len(sys.argv) > 1 else Path(__file__).with_name("all_opcodes.a51")
    out.write_text(generate(), encoding="ascii", newline="\n")
    return 0


if __name__ == "__main__":
    sys.exit(main())
